import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { DatabaseSync } from 'node:sqlite';

test('Master spec §1/§2: browser key proof and explicit Owner approval enforce role and single use', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aion-browser-pairing-'));
  process.env.AION_SECURITY_DB_PATH = path.join(dir, 'security.sqlite');
  const store = await import('../src/services/identity-store.js');
  t.after(async () => { await store.resetIdentityStoreForTests(); fs.rmSync(dir, { recursive: true, force: true }); });
  const ownerKey = crypto.generateKeyPairSync('ed25519');
  const owner = await store.enrollInitialOwner({ publicKey: ownerKey.publicKey.export({ type: 'spki', format: 'pem' }) });
  const actor = { role: 'owner', deviceId: owner.deviceId }, hostname = 'example.example.ts.net';
  await assert.rejects(store.createBrowserPairingInvitation({ hostname, role: 'owner' }, actor));
  await assert.rejects(store.createBrowserPairingInvitation({ hostname }, { role: 'limited' }));
  const invitation = await store.createBrowserPairingInvitation({ hostname, role: 'trusted' }, actor);
  await assert.rejects(store.getBrowserPairingChallenge(invitation.invitationId, 'other.example.ts.net'));
  const challenge = await store.getBrowserPairingChallenge(invitation.invitationId, hostname);
  const phone = crypto.generateKeyPairSync('ed25519'), publicKey = phone.publicKey.export({ type: 'spki', format: 'pem' });
  const digest = crypto.createHash('sha256').update(publicKey).digest('hex');
  const payload = `aion-browser-pairing-v1:${challenge.invitationId}:${hostname}:trusted:${challenge.challenge}:${digest}`;
  const signature = crypto.sign(null, Buffer.from(payload), phone.privateKey).toString('base64url');
  const claim = { invitationId: invitation.invitationId, hostname, publicKey, signature, name: 'Test phone' };
  await assert.rejects(store.claimBrowserPairingInvitation({ ...claim, signature: crypto.randomBytes(64).toString('base64url') }), /proof/);
  await assert.rejects(store.approveBrowserPairingInvitation({ invitationId: invitation.invitationId, verificationCode: '000000' }, actor));
  const pending = await store.claimBrowserPairingInvitation(claim);
  assert.match(pending.verificationCode, /^\d{6}$/);
  await assert.rejects(store.claimBrowserPairingInvitation(claim));
  const requests = await store.listBrowserPairingRequests(actor);
  assert.equal(requests[0].verificationCode, pending.verificationCode);
  const badCode = pending.verificationCode === '000000' ? '000001' : '000000';
  await assert.rejects(store.approveBrowserPairingInvitation({ invitationId: invitation.invitationId, verificationCode: badCode }, actor), /code/);
  await assert.rejects(store.approveBrowserPairingInvitation({ invitationId: invitation.invitationId, verificationCode: pending.verificationCode }, { role: 'limited' }));
  const approved = await store.approveBrowserPairingInvitation({ invitationId: invitation.invitationId, verificationCode: pending.verificationCode }, actor);
  assert.equal(approved.role, 'trusted'); assert.equal(approved.capabilities.includes('sync:replicate'), false);
  await assert.rejects(store.approveBrowserPairingInvitation({ invitationId: invitation.invitationId, verificationCode: pending.verificationCode }, actor));
  const login = await store.createChallenge(approved.deviceId);
  const session = await store.authenticateChallenge({ challengeId: login.challengeId, signature: crypto.sign(null, Buffer.from(login.signingPayload), phone.privateKey).toString('base64url') });
  assert.ok(await store.authorize(session.token, 'conversation:read'));
  await store.revokeDevice(approved.deviceId, actor);
  assert.equal(await store.authorize(session.token, 'conversation:read'), null);
  const expired = await store.createBrowserPairingInvitation({ hostname }, actor);
  const db = new DatabaseSync(process.env.AION_SECURITY_DB_PATH);
  db.prepare("UPDATE browser_pairing_invitations SET expires_at='2000-01-01T00:00:00.000Z' WHERE id=?").run(expired.invitationId); db.close();
  await assert.rejects(store.getBrowserPairingChallenge(expired.invitationId, hostname), /expired/);
});
